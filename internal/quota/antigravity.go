func antigravityCachedToken(rt string) string {
	d, e := readDoc(configPath("antigravity-token.json"))
	if e != nil || str(d["fingerprint"]) != fmt.Sprintf("%x", sha256.Sum256([]byte(rt))) || when(d["expires_at_ms"]) <= time.Now().Unix()+60 {
		return ""
	}
	return str(d["access_token"])
}
func antigravitySaveToken(rt, token string, exp int64) {
	_ = atomicWrite(configPath("antigravity-token.json"), object{"access_token": token, "expires_at_ms": exp * 1000, "fingerprint": fmt.Sprintf("%x", sha256.Sum256([]byte(rt)))})
}
